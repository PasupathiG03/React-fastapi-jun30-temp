import uuid
from datetime import datetime, timezone
from sqlalchemy import (
    Column,
    DateTime,
    Float,
    ForeignKey,
    Integer,
    JSON,
    String,
    Text,
    func,
)
from sqlalchemy.orm import relationship

from app.core.database import Base
from app.models.user import User  # noqa: F401
from app.models.bigbasket import ImageBatch, BatchImage  # noqa: F401


class GeminiApiLog(Base):
    """
    Tracks Google Gemini Multimodal Vision API token metrics, costs, and classifications.
    Follows official Google AI Studio token definitions:
    - prompt_tokens: Text prompt tokens + image tokens (258 tokens per 384x384 image or 768x768 tile)
    - candidates_tokens: Output structured JSON tokens generated by model
    - thoughts_tokens: Chain-of-thought reasoning tokens (thoughtsTokenCount)
    - total_tokens: prompt_tokens + candidates_tokens + thoughts_tokens
    - estimated_cost_usd: Calculated per official rates ($0.30/1M input, $2.50/1M output)
    """

    __tablename__ = "gemini_api_logs"

    id = Column(Integer, primary_key=True, index=True)
    request_id = Column(String(64), default=lambda: str(uuid.uuid4()), index=True, nullable=False)
    user_id = Column(Integer, ForeignKey("users.id", ondelete="SET NULL"), nullable=True, index=True)
    batch_id = Column(Integer, ForeignKey("image_batches.id", ondelete="SET NULL"), nullable=True, index=True)
    image_id = Column(Integer, ForeignKey("batch_images.id", ondelete="SET NULL"), nullable=True, index=True)

    # Context & identifiers
    bbid = Column(String(100), nullable=True, index=True)
    filename = Column(String(255), nullable=True)
    model_name = Column(String(100), default="gemini-3.5-flash-lite", nullable=False, index=True)
    endpoint = Column(String(255), default="generateContent", nullable=False)

    # Status: SUCCESS, CACHE_HIT, FALLBACK, ERROR
    status = Column(String(50), default="SUCCESS", nullable=False, index=True)
    status_code = Column(Integer, default=200, nullable=False)

    # Official Token Metrics (from Gemini API usageMetadata)
    prompt_tokens = Column(Integer, default=0, nullable=False)        # Input tokens (text + image tiles)
    candidates_tokens = Column(Integer, default=0, nullable=False)    # Output response tokens
    thoughts_tokens = Column(Integer, default=0, nullable=False)      # Reasoning / thinking tokens
    total_tokens = Column(Integer, default=0, nullable=False)         # Total tokens billed
    cached_tokens = Column(Integer, default=0, nullable=False)        # Cached prompt tokens

    # Official Billing & Savings ($ USD)
    estimated_cost_usd = Column(Float, default=0.0, nullable=False)   # Net API cost incurred
    cost_saved_usd = Column(Float, default=0.0, nullable=False)       # Cost saved by cache or fallback

    # Performance
    latency_ms = Column(Float, default=0.0, nullable=False)

    # Classification Output
    primary_category = Column(String(50), nullable=True, index=True)  # FOOD, NON_FOOD, KITCHEN_ITEMS, UNKNOWN
    subcategory = Column(String(100), nullable=True)
    product_type = Column(String(100), nullable=True)
    classification_confidence = Column(Float, nullable=True)
    image_type = Column(String(50), nullable=True)                    # FOP, BOP, etc.
    requires_manual_review = Column(Integer, default=0, nullable=False)

    # Rich Metadata
    materials = Column(JSON, nullable=True)
    components = Column(JSON, nullable=True)
    visual_properties = Column(JSON, nullable=True)
    error_message = Column(Text, nullable=True)
    metadata_payload = Column(JSON, nullable=True)

    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False, index=True)

    # Relationships
    user = relationship("User", foreign_keys=[user_id])
    batch = relationship("ImageBatch", foreign_keys=[batch_id])
    image = relationship("BatchImage", foreign_keys=[image_id])

    def __repr__(self) -> str:
        return f"<GeminiApiLog id={self.id} model={self.model_name!r} status={self.status!r} tokens={self.total_tokens}>"

